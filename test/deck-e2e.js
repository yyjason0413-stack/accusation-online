'use strict';
// 組牌畫面：建立混搭牌組（白狐 12 + 鴉 4 + 放逐者 4）、儲存、用它開 AI 對局，並截圖 390x844
const { chromium } = require('playwright');
const BASE = process.argv[2] || 'http://localhost:8787';
const SHOTS = process.argv[3] || '/workspace/accusation/shots';
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('dialog', d => d.accept());
  await page.goto(BASE); await page.waitForTimeout(800);
  await page.click('#decks');
  await page.screenshot({ path: `${SHOTS}/deck-list-390x844.png` });
  await page.click('#newDeck');
  await page.click('[data-leader="fox01"]');
  const fox = ['fox05', 'fox06', 'fox07', 'fox08', 'fox09', 'fox10', 'fox11', 'fox12', 'fox13', 'fox14', 'fox15', 'fox16'];
  for (const id of fox) await page.click(`[data-card="${id}"]`);
  await page.click('[data-tab="鴉教團"]');
  for (const id of ['cro05', 'cro13', 'cro21', 'cro24']) await page.click(`[data-card="${id}"]`);
  await page.click('[data-tab="放逐者"]');
  for (const id of ['exi03', 'exi11', 'exi31']) await page.click(`[data-card="${id}"]`);
  await page.screenshot({ path: `${SHOTS}/deck-builder-invalid-390x844.png` });
  await page.click(`[data-card="exi33"]`);
  await page.fill('#dname', '狐鴉放逐');
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.waitForTimeout(300);
  await page.screenshot({ path: `${SHOTS}/deck-builder-390x844.png` });
  const ok = await page.$('.okline');
  await page.click('#save');
  await page.click('#back');
  const lobbyName = await page.textContent('.deckpick .ztitle');
  await page.click('#ai');
  await page.waitForSelector('.game');
  await page.waitForTimeout(1500);
  console.log(JSON.stringify({ valid: !!ok, lobbyName, errors }));
  await browser.close();
  process.exit(ok && !errors.length ? 0 : 1);
})().catch(e => { console.error(e); process.exit(1); });
